// create a card
function getrestaurants(restaurant){
  const root = document.getElementById("root");
    restaurant.forEach(restaurant=> {

      //create card
      //1.image
      //2,card_content
      //.   1.card header(name and rating)
      //.    2. card_foter(food type and price)
      //.    3. card_location(res location ,distnace)
    const card =   document.createElement("div");
    card.classList.add('card'); // add css of card & make class

   // create image 
   const image= document.createElement("img");
   
    image.src = `images/${restaurant.image}.jpeg`;

   // card content
   const card_content = document.createElement("div");
   card_content.classList.add("card-content") // add css of card-content
   
   //card header
   const card_header = document.createElement("div");
   card_header.classList.add("card-header")

   const h3 = document.createElement("h3");
   h3.textContent = restaurant.name;

   const rate = document.createElement("span");
   rate.textContent= "Rating:" + restaurant.rating;
   rate.style.backgroundColor="orange";
   rate.style.fontWeight="bold";
   rate.style.padding="4px";
   rate.style.borderRadius="5px";
   
          //card_header ke andr daale
   card_header.appendChild(h3);
   card_header.appendChild(rate);
   
   



  // card footer
  const card_footer = document.createElement("div");
   card_footer.classList.add("card-footer")

   const food = document.createElement("span");
   food.textContent = restaurant.foodtype;

   const price = document.createElement("span");
   price.textContent= "$"+restaurant.price;
      
       //card_fotter ke andr dale 
   card_footer.appendChild(food);
   card_footer.appendChild(price);
   //card location
   const card_location = document.createElement("div");
   card_location.classList.add("card-location")

   const location = document.createElement("span");
   location.textContent = restaurant.locations;

   const distances = document.createElement("span");
   distances.textContent=restaurant.distance+"km";
        // card_location me daalo 
 
   card_location.appendChild(location);
   card_location.appendChild(distances);
   // card-content me daalo
   card_content.appendChild(card_header);
   card_content.appendChild(card_footer);
   card_content.appendChild(card_location);
    
   // sbko card me dalo
   card.appendChild(image);
   card.appendChild(card_content)
   // html vaale root div me card ko dalo
   root.appendChild(card);
    });
}
